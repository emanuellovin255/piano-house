// Scans public/media, records intrinsic dimensions and generates a tiny
// base64 blur placeholder for every photo. Output: src/data/images.generated.ts
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const MEDIA = path.join(ROOT, "public", "media");
const DIRS = ["gallery", "new", "hero", "units/city", "units/travel", "units/tango", "units/cover"];

async function describe(dir, file) {
  const abs = path.join(MEDIA, dir, file);
  const img = sharp(abs);
  const { width, height } = await img.metadata();
  const buf = await img.resize(16, null, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  return {
    src: `/media/${dir}/${file}`,
    width,
    height,
    blurDataURL: `data:image/webp;base64,${buf.toString("base64")}`,
  };
}

const manifest = {};
for (const dir of DIRS) {
  const files = (await readdir(path.join(MEDIA, dir)))
    .filter((f) => /\.(jpe?g|png)$/i.test(f))
    .sort();
  manifest[dir] = await Promise.all(files.map((f) => describe(dir, f)));
  console.log(`${dir}: ${manifest[dir].length}`);
}

const body = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.
export type MediaImage = {
  src: string;
  width: number;
  height: number;
  blurDataURL: string;
};

export const media = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, readonly MediaImage[]>;

export type MediaKey = keyof typeof media;
`;
await writeFile(path.join(ROOT, "src", "data", "images.generated.ts"), body);
console.log("wrote src/data/images.generated.ts");
